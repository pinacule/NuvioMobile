#!/usr/bin/env python3
"""Generate secrets for the Nuvio self-hosted sync backend.

Produces:
  JWT_SECRET       32 random bytes, hex-encoded. Shared by PostgREST and GoTrue.
  ANON_KEY         HS256 JWT {iss:"supabase", role:"anon", iat, exp} signed
                   with JWT_SECRET. Publishable; embedded in
                   /.well-known/nuvio and handed to the app.
  SERVICE_ROLE_KEY HS256 JWT {iss:"supabase", role:"service_role", iat, exp}
                   signed with JWT_SECRET. Bypasses PostgREST RLS — keep private.
  POSTGRES_PASSWORD  24 random bytes, base64, for the postgres superuser role.

Usage:
  python3 scripts/gen-keys.py            # print a ready-to-paste .env snippet
  python3 scripts/gen-keys.py > .env     # then edit NUVIO_BACKEND_URL in .env
  python3 scripts/gen-keys.py --help

Pure stdlib: hashlib, hmac, base64, json, secrets, time, argparse.
"""

import argparse
import base64
import hashlib
import hmac
import json
import secrets
import time

# Supabase JWTs are valid for a long time; 10 years matches Supabase's
# own hosted key lifetime convention.
TEN_YEARS_SECONDS = 10 * 365 * 86400


def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def mint_jwt(secret_hex: bytes, role: str, now: int) -> str:
    header = b64url(
        json.dumps({"alg": "HS256", "typ": "JWT"}, separators=(",", ":")).encode()
    )
    payload = b64url(
        json.dumps(
            {
                "iss": "supabase",
                "role": role,
                "iat": now,
                "exp": now + TEN_YEARS_SECONDS,
            },
            separators=(",", ":"),
        ).encode()
    )
    signing_input = f"{header}.{payload}".encode()
    signature = b64url(hmac.new(secret_hex, signing_input, hashlib.sha256).digest())
    return f"{header}.{payload}.{signature}"


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate JWT_SECRET, anon/service_role JWTs and a Postgres "
        "password for the Nuvio self-hosted sync backend.",
        epilog="Example: python3 scripts/gen-keys.py > .env "
        "# then set NUVIO_BACKEND_URL in .env",
    )
    parser.parse_args()

    jwt_secret = secrets.token_hex(32)  # 32 bytes, hex-encoded
    secret_bytes = bytes.fromhex(jwt_secret)
    now = int(time.time())

    anon_key = mint_jwt(secret_bytes, "anon", now)
    service_role_key = mint_jwt(secret_bytes, "service_role", now)
    postgres_password = secrets.token_urlsafe(24)

    print("# Generated by scripts/gen-keys.py — do not commit this file.")
    print(f"POSTGRES_PASSWORD={postgres_password}")
    print(f"JWT_SECRET={jwt_secret}")
    print(f"ANON_KEY={anon_key}")
    print(f"SERVICE_ROLE_KEY={service_role_key}")
    print("NUVIO_BACKEND_URL=https://sync.example.com")


if __name__ == "__main__":
    main()
